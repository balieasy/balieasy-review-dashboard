import {build} from 'esbuild';
import assert from 'node:assert/strict';
await build({entryPoints:['app/periods.ts'],bundle:true,format:'esm',platform:'node',outfile:'.sites-runtime/tests/trend-intervals.mjs'});
const {calendarInterval,timeSeries,rangeCounts,intervalLabel,seriesIntervals,daysBetween}=await import('../.sites-runtime/tests/trend-intervals.mjs');
assert.deepEqual(seriesIntervals.map(x=>x.value),['day','week','month','quarter']);
assert.deepEqual(calendarInterval('2026-10-01','week'),{start:'2026-09-28',end:'2026-10-04'});
assert.deepEqual(calendarInterval('2026-10-04','week'),{start:'2026-09-28',end:'2026-10-04'});
assert.deepEqual(calendarInterval('2026-10-05','week'),{start:'2026-10-05',end:'2026-10-11'});
assert.deepEqual(calendarInterval('2024-02-29','month'),{start:'2024-02-01',end:'2024-02-29'});
assert.deepEqual(calendarInterval('2024-02-29','quarter'),{start:'2024-01-01',end:'2024-03-31'});
assert.deepEqual(calendarInterval('2026-12-31','quarter'),{start:'2026-10-01',end:'2026-12-31'});
assert.deepEqual(calendarInterval('2026-12-31','week'),{start:'2026-12-28',end:'2027-01-03'});
console.log('PASS day/week/month/quarter choices, Monday weeks, leap months, quarter/year boundaries');
const range={start:'2026-10-01',end:'2026-10-22',previousStart:'2026-09-01',previousEnd:'2026-09-22'};
const review=(id,created)=>({id,created,rating:5,name:'Test',comment:'',replied:false,photos:0,videos:0});
const reviews=[review('before','2026-09-30T15:59:00Z'),review('a','2026-09-30T16:00:00Z'),review('b','2026-10-05T04:00:00Z'),review('last','2026-10-22T15:59:59Z'),review('after','2026-10-22T16:00:00Z'),review('p','2026-09-10T04:00:00Z')];
for(const interval of seriesIntervals.map(x=>x.value)){
 const points=timeSeries(reviews,range,interval),counts=rangeCounts(reviews,range);
 assert.equal(points.reduce((sum,p)=>sum+p.current,0),counts.current);
 assert.equal(points.reduce((sum,p)=>sum+p.previous,0),counts.previous);
 const chosen=points.filter(p=>p.start);assert.equal(chosen[0].start,range.start);assert.equal(chosen.at(-1).end,range.end);
 assert.equal(chosen.reduce((sum,p)=>sum+daysBetween(p.start,p.end),0),daysBetween(range.start,range.end));
}
assert.equal(rangeCounts(reviews,range).current,3);
console.log('PASS all intervals conserve current/comparison totals, cover period exactly, and respect WITA midnight');
const weeks=timeSeries(reviews,range,'week');
assert.deepEqual(weeks.map(p=>[p.start,p.end,p.partial]),[['2026-10-01','2026-10-04',true],['2026-10-05','2026-10-11',false],['2026-10-12','2026-10-18',false],['2026-10-19','2026-10-22',true]]);
assert.equal(timeSeries(reviews,range,'day').filter(p=>p.start).length,22);
assert.equal(timeSeries(reviews,range,'month')[0].partial,true);
assert.equal(timeSeries(reviews,range,'quarter')[0].partial,true);
assert.equal(intervalLabel('2026-10-01','quarter'),'Q4 2026');
console.log('PASS partial edge intervals are explicit, exact weekly boundaries and quarter labels');
const crossing={start:'2025-11-18',end:'2026-04-04',previousStart:'2025-05-04',previousEnd:'2025-11-17'};
assert.deepEqual(timeSeries([],crossing,'quarter').filter(p=>p.start).map(p=>[p.start,p.end,p.partial]),[['2025-11-18','2025-12-31',true],['2026-01-01','2026-03-31',false],['2026-04-01','2026-04-04',true]]);
const unequal={start:'2026-02-01',end:'2026-02-28',previousStart:'2026-01-01',previousEnd:'2026-01-31'};
const extra=timeSeries([review('late','2026-01-31T04:00:00Z')],unequal,'day');assert.equal(extra.length,31);assert.equal(extra[30].start,'');assert.equal(extra[30].previous,1);
console.log('PASS calendar grouping crosses years and retains extra comparison intervals');
const long={start:'2020-01-01',end:'2026-10-22',previousStart:'2019-01-01',previousEnd:'2019-01-31'},longSeries=timeSeries([review('tail','2026-10-22T04:00:00Z')],long,'day');
assert.equal(longSeries.length,daysBetween(long.start,long.end));assert.equal(longSeries.at(-1).current,1);
console.log('PASS long daily ranges retain their last review without silent truncation');
